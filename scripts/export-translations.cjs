const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'i18n.js'), 'utf8').replaceAll('\r\n', '\n');
const boundary = source.indexOf('(() => {\n  const textEntries = [];');
if (boundary < 0) throw new Error('Translation dictionary boundary not found');
const dictionary = vm.runInNewContext(source.slice(0, boundary) + '\nportfolioTranslations');
const dir = path.join(root, 'tmp', 'pdfs');
fs.mkdirSync(dir, {recursive: true});
fs.writeFileSync(path.join(dir, 'translations.json'), JSON.stringify(dictionary));
console.log('Exported translation dictionary for CV generation.');
